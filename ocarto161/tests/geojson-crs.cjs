const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const geo=require('../geo-crs.js');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('  function normalizeCrsName');
const end=html.indexOf("  $('geoFile').onchange",start);
assert.ok(start>=0&&end>start,'No se encontraron validadores CRS');
let target='EPSG:25830';
const context={S:{georef:{},cloudTransform:null},$:()=>({value:target}),OcartoGeoCrs:geo};
vm.createContext(context);vm.runInContext(html.slice(start,end),context);
const features=[{type:'Feature',properties:{},geometry:{type:'Point',coordinates:[-3,40]}}];
const converted=context.validateGeoJsonCrs({metadata:{crs:'urn:ogc:def:crs:EPSG::4326'}},features);
assert.equal(converted.reprojected,true);assert.equal(converted.target,'EPSG:25830');assert.equal(converted.approximateDatum,true);
const projected=geo.transformPositions([-3,40,18],'EPSG:4326','EPSG:25830');
assert.ok(Math.abs(projected[0]-500000)<0.1);assert.ok(projected[1]>4400000&&projected[1]<4500000);assert.equal(projected[2],18);
const polygon=geo.transformPositions([[[ -3,40],[ -2.9,40],[ -3,40.1],[ -3,40]],[[ -2.98,40.02],[ -2.97,40.02],[ -2.98,40.03],[ -2.98,40.02]]],'EPSG:4326','EPSG:25830');assert.equal(polygon.length,2);assert.equal(polygon[1].length,4);assert.ok(Math.abs(polygon[0][0][0]-500000)<0.1);
assert.equal(context.validateGeoJsonCrs({metadata:{crs:'EPSG:3857'}},features).reprojected,true);
const standard=context.validateGeoJsonCrs({},features);assert.equal(standard.source,'EPSG:4326');assert.equal(standard.reprojected,true);
assert.throws(()=>context.validateGeoJsonCrs({metadata:{crs:'local',coordinate_status:'local'}},features),/No se puede convertir/);
assert.throws(()=>context.validateGeoJsonCrs({metadata:{coordinate_status:'cloud',crs:'unspecified'}},features),/no declara su CRS/);
assert.throws(()=>context.validateGeoJsonCrs({metadata:{coordinate_status:'georeferenced',crs:null}},features),/no declara su CRS/);
assert.throws(()=>context.validateGeoJsonCrs({metadata:{crs:'EPSG:25830'}},[{properties:{coordinate_reference_system:'EPSG:4326'}}]),/mezcla varios CRS/);
target='';assert.throws(()=>context.validateGeoJsonCrs({metadata:{crs:'EPSG:25830'}},features),/Indica el CRS/);
console.log('OK: importación CRS coincide o reproyecta EPSG:4326 a UTM compatible; los demás casos se bloquean');
{
  const autoContext={S:{features:[],candidates:[],points:[],templates:[],cloudTransform:null,georef:null,mapCrsAuto:true},$:()=>({value:'EPSG:32630'}),OcartoGeoCrs:geo};
  vm.createContext(autoContext);vm.runInContext(html.slice(start,end),autoContext);
  const located=autoContext.validateGeoJsonCrs({},[{type:'Feature',properties:{},geometry:{type:'Point',coordinates:[-9,40]}}]);
  assert.equal(located.automaticZone,true);assert.equal(located.target,'EPSG:32629');assert.equal(autoContext.S.mapCrsAuto,false);
  const explicitContext={S:{features:[],candidates:[],points:[],templates:[],cloudTransform:null,georef:null,mapCrsAuto:false},$:()=>({value:'EPSG:32631'}),OcartoGeoCrs:geo};
  vm.createContext(explicitContext);vm.runInContext(html.slice(start,end),explicitContext);
  const explicit=explicitContext.validateGeoJsonCrs({},[{type:'Feature',properties:{},geometry:{type:'Point',coordinates:[-3,40]}}]);
  assert.equal(explicit.automaticZone,false);assert.equal(explicit.target,'EPSG:32631');
}
