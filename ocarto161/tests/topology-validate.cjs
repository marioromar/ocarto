const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const {validate,validatePolygon}=require('../topology-tools.js');
assert.equal(validate([[0,0],[2,0],[2,2],[0,2]],true).valid,true);
assert.equal(validate([[0,0],[2,2],[0,2],[2,0]],true).valid,false);
assert.equal(validate([[0,0],[2,0],[2,2]]).valid,true);
assert.ok(validate([[0,0],[2,2],[0,2],[2,0]]).issues.some(x=>x.includes('auto-intersección')));
assert.ok(validate([[0,0],[2,0],[1,0]]).issues.some(x=>x.includes('retroceso')));
assert.ok(validate([[0,0],[0,0],[2,0]]).issues.some(x=>x.includes('duplicados')));
assert.ok(validate(Array.from({length:2501},(_,i)=>[i,0])).issues.some(x=>x.includes('demasiado compleja')));
const outer=[[0,0],[10,0],[10,10],[0,10]],inside=[[2,2],[4,2],[4,4],[2,4]];
assert.deepEqual(validatePolygon(outer,[inside]),{valid:true,issues:[]});
assert.ok(validatePolygon(outer,[[[12,12],[14,12],[14,14],[12,14]]]).issues.some(x=>x.includes('queda fuera')));
assert.ok(validatePolygon(outer,[[[8,3],[12,3],[12,5],[8,5]]]).issues.some(x=>x.includes('cruza o toca')));
assert.ok(validatePolygon(outer,[inside,[[3,3],[5,3],[5,5],[3,5]]]).issues.some(x=>x.includes('se solapan')));
assert.ok(validatePolygon(outer,[[[2,2],[4,4],[2,4],[4,2]]]).issues.some(x=>x.includes('auto-intersección')));
assert.ok(validatePolygon(outer,[Array.from({length:2500},(_,i)=>[i,0])]).issues.some(x=>x.includes('demasiado compleja')));
assert.match(html,/OcartoTopologyTools\.validatePolygon\(coords,/,'advanced validator checks holes on selected areas');
assert.match(html,/window\.sampledPoints\(f\.points,f\.type==='area',20\)/,'Bezier outlines are flattened before checking crossings');
assert.match(html,/Revisar geometrías/,'ambiguous findings are reported for review, not as definitive errors');
console.log('✓ validación topológica de líneas, contornos exteriores y agujeros');
