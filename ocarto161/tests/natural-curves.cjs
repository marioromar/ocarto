const assert=require('node:assert/strict');
const fs=require('node:fs');
const {apply}=require('../natural-curves.js');
const html=fs.readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const line={type:'line',points:[{x:0,y:0},{x:4,y:4},{x:8,y:0}]};
const curved=apply(line);
assert.equal(curved.curve,'bezier');
assert.equal(curved.naturalCurve,'cubic-bezier');
assert.ok(curved.points.every(p=>p.tangent&&Number.isFinite(p.tangent.x)&&Number.isFinite(p.tangent.y)));
assert.deepEqual(line.points[0],{x:0,y:0},'does not mutate source geometry');
const a=curved.points[0],b=curved.points[1],midY=.375*(a.y+a.tangent.y)+.375*(b.y-b.tangent.y)+.125*b.y;
assert.ok(Math.abs(midY-2)>.1,'cubic segment visibly differs from a straight segment');
const area={type:'area',points:[{x:0,y:0},{x:10,y:0},{x:10,y:10},{x:0,y:10}],holes:[[{x:2,y:2},{x:4,y:2},{x:3,y:4}]]};
const smooth=apply(area);
assert.equal(smooth.curve,'bezier');
assert.equal(smooth.holes[0].length,3);
assert.ok(smooth.holes[0].every(p=>p.tangent));
const building=apply({...area,candidateKind:'building'});
assert.equal(building.curve,undefined,'building outlines remain straight');
assert.equal(apply({...area,candidateProperties:{kind:'edificio'}}).curve,undefined);
assert.equal(apply({...area,symbol:'ruin-area'}).curve,undefined,'ruin contours retain their corner vertices');
assert.equal(apply({...area,candidateProperties:{category:'ruina'}}).curve,undefined,'ruin candidates retain their corner vertices');
assert.match(html,/function finishFreehand\(\)[\s\S]*?OcartoNaturalCurves\.apply\(feature\)/,'completed freehand drawings become editable natural curves');
assert.match(html,/angularFeature\?points\.map\(p=>\(\{\.\.\.p,vertexType:'corner'\}\)\):points/,'freehand buildings and ruins keep corner vertices');
assert.throws(()=>apply({type:'area',points:[{x:0,y:0},{x:1,y:0}]}),/Geometría natural inválida/);
console.log('✓ curvas Bézier naturales para líneas y áreas; edificios rectos y fuentes intactas');
