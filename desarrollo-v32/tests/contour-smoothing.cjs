const assert=require('node:assert/strict');
const {smooth}=require('../contour-smoothing.js');
const F=(coords,elevation=100)=>({type:'Feature',properties:{elevation,unsmoothed:true},geometry:{type:'LineString',coordinates:coords}});
const source=[F([[0,0],[1,.2],[2,0],[3,.2],[4,0]])];
const snapshot=JSON.stringify(source);
assert.deepEqual(smooth(source,{intensity:0}).features[0].geometry.coordinates,source[0].geometry.coordinates);
const result=smooth(source,{intensity:70,protectedAngle:100,maxShift:.1});
assert.equal(result.features[0].properties.elevation,100);
assert.equal(result.features[0].geometry.coordinates.length,5);
assert.deepEqual(result.features[0].geometry.coordinates[0],[0,0]);
assert.deepEqual(result.features[0].geometry.coordinates[4],[4,0]);
assert.ok(result.moved>0);
assert.ok(result.features[0].geometry.coordinates.slice(1,4).every((p,i)=>Math.hypot(p[0]-source[0].geometry.coordinates[i+1][0],p[1]-source[0].geometry.coordinates[i+1][1])<=.10000001));
assert.equal(JSON.stringify(source),snapshot,'source unmodified');
const apex=F([[0,0],[1,0],[1,1],[2,1]]);
assert.deepEqual(smooth([apex],{intensity:100,protectedAngle:55}).features[0].geometry.coordinates,apex.geometry.coordinates,'protect corners');
const cycle=F([[0,0],[2,0],[2,2],[0,2],[0,0]]);
const c=smooth([cycle],{intensity:90,protectedAngle:180});
assert.deepEqual(c.features[0].geometry.coordinates[0],c.features[0].geometry.coordinates.at(-1),'preserve closure');
assert.equal(c.features[0].geometry.coordinates.length,5);
assert.throws(()=>smooth(source,{intensity:101}),/Intensidad/);
assert.throws(()=>smooth([F([[0,0],[NaN,1]])]),/Curva inválida/);
console.log('contour smoothing v20 OK');
