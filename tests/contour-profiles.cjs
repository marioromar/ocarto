const assert=require('node:assert/strict');
globalThis.OcartoContours=require('../contours.js');
globalThis.OcartoContourSmoothing=require('../contour-smoothing.js');
const P=require('../contour-profiles.js');
const rows=[];for(let y=0;y<8;y++)for(let x=0;x<8;x++)rows.push([x+.5,y+.5,1.37*x+0.81*y,3,'observada']);
const p=P.build(rows,1,5,{intensity:20});
assert.equal(p.detailInterval,1);assert.equal(p.interval,5);assert.ok(p.stats.detailSegments>p.stats.generalSegments);
assert.ok(p.detail.every(f=>f.properties.template&&f.properties.editable===false&&f.properties.unsmoothed));
assert.ok(p.general.every(f=>f.properties.editable===true));
assert.notEqual(p.detail,p.original);assert.notEqual(p.general,p.original);
const before=p.original[0].geometry.coordinates[0][0];p.general[0].geometry.coordinates[0][0]+=20;
assert.equal(p.original[0].geometry.coordinates[0][0],before,'General editing must not change originals');
assert.equal(P.geojson(p,'detail').properties.interval,1);
assert.equal(P.geojson(p,'general').properties.interval,5);
assert.throws(()=>P.detailInterval(5,6),/Equidistancias/);
assert.throws(()=>P.geojson(p,'wrong'),/Capa/);
assert.equal(P.detailInterval(2.5),.5);
console.log('✓ v21: curvado general y plantilla detallada 1 m independientes');
